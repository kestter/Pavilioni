function initAboutCarousel() {
  const root = document.getElementById("aboutCarousel");
  if (!root) return;

  const track = root.querySelector(".about-carousel-track");
  const slides = Array.from(track.children);
  const dotsWrap = document.getElementById("aboutCarouselDots");
  const prevBtn = document.getElementById("aboutCarouselPrev");
  const nextBtn = document.getElementById("aboutCarouselNext");

  if (slides.length <= 1) {
    if (prevBtn) prevBtn.hidden = true;
    if (nextBtn) nextBtn.hidden = true;
    return;
  }

  let index = 0;
  let startX = 0;
  let currentX = 0;
  let dragging = false;
  let width = root.clientWidth;

  slides.forEach((_, i) => {
    const dot = document.createElement("button");
    dot.type = "button";
    dot.className = "dot" + (i === 0 ? " active" : "");
    dot.setAttribute("role", "tab");
    dot.setAttribute("aria-label", `Go to photo ${i + 1}`);
    dot.addEventListener("click", () => goTo(i));
    dotsWrap.appendChild(dot);
  });
  const dots = Array.from(dotsWrap.children);

  function render(withTransition = true) {
    track.style.transition = withTransition ? "" : "none";
    track.style.transform = `translateX(-${index * 100}%)`;
    dots.forEach((d, i) => d.classList.toggle("active", i === index));
  }

  function goTo(i) {
    index = (i + slides.length) % slides.length;
    render();
  }

  if (prevBtn) prevBtn.addEventListener("click", () => goTo(index - 1));
  if (nextBtn) nextBtn.addEventListener("click", () => goTo(index + 1));

  window.addEventListener("resize", () => {
    width = root.clientWidth;
    render(false);
  });

  const onStart = (x) => {
    dragging = true;
    startX = x;
    currentX = x;
    track.style.transition = "none";
  };
  const onMove = (x) => {
    if (!dragging) return;
    currentX = x;
    const delta = currentX - startX;
    track.style.transform = `translateX(calc(-${index * 100}% + ${delta}px))`;
  };
  const onEnd = () => {
    if (!dragging) return;
    dragging = false;
    const delta = currentX - startX;
    const threshold = width * 0.15;
    if (delta > threshold) goTo(index - 1);
    else if (delta < -threshold) goTo(index + 1);
    else render();
  };

  root.addEventListener("touchstart", (e) => onStart(e.touches[0].clientX), { passive: true });
  root.addEventListener("touchmove", (e) => onMove(e.touches[0].clientX), { passive: true });
  root.addEventListener("touchend", onEnd);

  root.addEventListener("mousedown", (e) => {
    e.preventDefault();
    onStart(e.clientX);
  });
  window.addEventListener("mousemove", (e) => onMove(e.clientX));
  window.addEventListener("mouseup", onEnd);

  root.setAttribute("tabindex", "0");
  root.addEventListener("keydown", (e) => {
    if (e.key === "ArrowLeft") goTo(index - 1);
    if (e.key === "ArrowRight") goTo(index + 1);
  });

  render(false);
}




