function initLightbox() {
  const lightbox = document.getElementById("lightbox");
  const lightboxImg = document.getElementById("lightboxImg");
  const lightboxCaption = document.getElementById("lightboxCaption");
  const closeBtn = document.getElementById("lightboxClose");
  const prevBtn = document.getElementById("lightboxPrev");
  const nextBtn = document.getElementById("lightboxNext");

  if (!lightbox || !lightboxImg || !lightboxCaption || !closeBtn || !prevBtn || !nextBtn) return;

  let visibleImages = [];
  let currentIndex = 0;

  const getVisibleImages = () =>
    Array.from(document.querySelectorAll(".gallery-item:not(.hidden-item) img"));

  const showImage = (index) => {
    if (!visibleImages.length) return;
    currentIndex = (index + visibleImages.length) % visibleImages.length;
    const img = visibleImages[currentIndex];
    if (!img) return;

    lightboxImg.src = img.currentSrc || img.src;
    lightboxImg.alt = img.alt || "Gallery image";
    lightboxCaption.textContent = img.getAttribute("data-title-text") || img.getAttribute("data-title") || img.alt || "";
  };

  const openLightbox = (img) => {
    visibleImages = getVisibleImages();
    if (!visibleImages.length || !img) return;

    const matchIndex = visibleImages.indexOf(img);
    currentIndex = matchIndex >= 0 ? matchIndex : 0;
    showImage(currentIndex);

    lightbox.classList.add("open");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  };

  const closeLightbox = () => {
    lightbox.classList.remove("open");
    lightbox.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
  };

  document.querySelectorAll(".gallery-item img").forEach((img) => {
    img.addEventListener("click", (event) => {
      event.preventDefault();
      event.stopPropagation();
      openLightbox(img);
    });
  });

  closeBtn.addEventListener("click", closeLightbox);
  prevBtn.addEventListener("click", () => showImage(currentIndex - 1));
  nextBtn.addEventListener("click", () => showImage(currentIndex + 1));

  lightbox.addEventListener("click", (e) => {
    if (e.target === lightbox) closeLightbox();
  });

  document.addEventListener("keydown", (e) => {
    if (!lightbox.classList.contains("open")) return;
    if (e.key === "Escape") closeLightbox();
    if (e.key === "ArrowLeft") showImage(currentIndex - 1);
    if (e.key === "ArrowRight") showImage(currentIndex + 1);
  });
}


